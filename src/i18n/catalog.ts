const ALL: Record<Locale, Dict> = { he, en, ar, zh };

let current: Locale = "he";

export function getLocale(): Locale {
  return current;
}

export function setLocale(loc: Locale): void {
  current = loc;
  try {
    localStorage.setItem("cit_locale", loc);
  } catch {
    /* ignore */
  }
}

export function initLocale(): Locale {
  try {
    const saved = localStorage.getItem("cit_locale") as Locale | null;
    if (saved && ALL[saved]) current = saved;
  } catch {
    /* ignore */
  }
  return current;
}

export function t(
  key: string,
  locale: Locale = current,
  params?: Record<string, string | number>,
): string {
  let s = ALL[locale][key] ?? ALL.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function localeDir(loc: Locale = current): "rtl" | "ltr" {
  return LOCALES.find((l) => l.id === loc)?.dir ?? "rtl";
}

/** Listeners when locale changes (for non-React code) */
const localeListeners = new Set<() => void>();
export function onLocaleChange(fn: () => void): () => void {
  localeListeners.add(fn);
  return () => localeListeners.delete(fn);
}

export function setLocaleAndNotify(loc: Locale): void {
  setLocale(loc);
  for (const fn of localeListeners) fn();
}
