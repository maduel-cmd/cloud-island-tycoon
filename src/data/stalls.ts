export function getStall(id: string): StallDef | undefined {
  // תאימות לשמירות ישנות עם hat_balloon
  const key = id === "hat_balloon" ? "balloon_vendor" : id;
  return STALLS.find((s) => s.id === key);
}

export function stallStockCap(def: StallDef, tier: number): number {
  return Math.round(def.stockCapacity * (1 + (tier - 1) * 0.25));
}

export function stallPrice(def: StallDef, tier: number): number {
  return Math.round(def.productPrice * (1 + (tier - 1) * 0.15));
}

export function stallUpgradeCost(def: StallDef, currentTier: number): number {
  if (currentTier >= 5) return Infinity;
  return Math.round(280 * def.productPrice * 0.35 * currentTier * currentTier);
}

export function stallBuildCost(def: StallDef): number {
  return Math.round(180 + def.productPrice * 18);
}
