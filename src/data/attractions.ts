export function getAttraction(id: string): AttractionDef | undefined {
  return ATTRACTIONS.find((a) => a.id === id);
}

export function tierMultiplier(tier: number): number {
  const t = Math.max(1, Math.min(5, tier));
  return 1 + (t - 1) * 0.28;
}

export function attractionCapacity(def: AttractionDef, tier: number): number {
  return Math.round(def.baseCapacity * tierMultiplier(tier));
}

export function attractionPrice(def: AttractionDef, tier: number): number {
  return Math.round(def.baseTicketPrice * tierMultiplier(tier));
}

export function attractionUpgradeCost(def: AttractionDef, currentTier: number): number {
  if (currentTier >= 5) return Infinity;
  return Math.round(400 * def.excitementScore * 0.12 * currentTier * currentTier);
}
